import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
p.on("pageerror", (e) => console.log("pageerror:", e.message));
const hunt = async (name) => {
  await p.locator(".tab", { hasText: name }).click();
  await p.getByTestId("hunt").click();
  await p.getByText(/start hunt|hunt again/).click();
  await p.waitForSelector(".cell.fail", { timeout: 20000 });
  await p.locator(".cell.fail").first().click();
  await p.waitForSelector(".verdict h1");
  await p.waitForTimeout(1200);
};
await p.goto("http://127.0.0.1:7420/?skip");
await p.waitForTimeout(800);
await hunt("philosophers");
await p.locator(".insp-tab", { hasText: "concurrency" }).click();
await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/5-deadlock.png` });
await hunt("checkout");
await p.screenshot({ path: `${out}/6-checkout.png` });
await hunt("bank");
await p.locator(".insp-tab", { hasText: "state" }).click();
await p.locator(".var .name", { hasText: /^balance$/ }).click();
await p.waitForTimeout(900);
await p.locator(".chip", { hasText: "write it up" }).click();
await p.waitForTimeout(900);
await p.screenshot({ path: `${out}/7-wave.png` });
await p.locator(".chip", { hasText: "diff against" }).click();
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/8-diff.png` });
await b.close();
