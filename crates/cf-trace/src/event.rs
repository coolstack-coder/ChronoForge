use serde::{Deserialize, Serialize};

use crate::value::{Loc, Val};

pub type Step = u64;
pub type Tid = u32;

/// The *recording*: every nondeterministic decision the VM made, in order.
///
/// This is the only thing replay needs. Everything else in a trace can be
/// regenerated from (program, NondetLog), which is why recordings stay tiny.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum NondetEvent {
    /// Scheduler switched to `tid` right before executing `step`.
    Schedule {
        step: Step,
        tid: Tid,
    },
    Rand {
        step: Step,
        value: i64,
    },
    Clock {
        step: Step,
        value: i64,
    },
    Input {
        step: Step,
        value: String,
    },
}

impl NondetEvent {
    pub fn step(&self) -> Step {
        match self {
            NondetEvent::Schedule { step, .. }
            | NondetEvent::Rand { step, .. }
            | NondetEvent::Clock { step, .. }
            | NondetEvent::Input { step, .. } => *step,
        }
    }
}

/// Coarse category of the instruction that ran. Enough for the UI to colour
/// the timeline without shipping the whole instruction set around.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum OpTag {
    Const,
    Load,
    Store,
    Arith,
    Compare,
    Jump,
    Branch,
    Call,
    Return,
    Array,
    Index,
    StoreIndex,
    Builtin,
    Spawn,
    Join,
    Lock,
    Unlock,
    Yield,
    Assert,
    Print,
    Nondet,
    Halt,
    Pop,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Read {
    pub loc: Loc,
    pub val: Val,
    /// Step that produced the value we just read (the "last writer").
    pub writer: Option<Step>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Write {
    pub loc: Loc,
    pub old: Val,
    pub new: Val,
}

/// Synchronisation that creates happens-before edges between threads.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum SyncOp {
    Spawn {
        child: Tid,
    },
    Join {
        target: Tid,
    },
    Acquire {
        mutex: u32,
    },
    Release {
        mutex: u32,
    },
    /// Tried to take a mutex someone else holds. No HB edge, but the UI and
    /// the deadlock detector care.
    BlockLock {
        mutex: u32,
        owner: Tid,
    },
    BlockJoin {
        target: Tid,
    },
    ThreadExit,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum NondetKind {
    Rand,
    Clock,
    Input,
}

/// One executed instruction, fully instrumented. Regenerated by replay.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct StepEvent {
    pub step: Step,
    pub tid: Tid,
    pub func: u32,
    pub pc: u32,
    pub line: u32,
    pub op: OpTag,
    pub reads: Vec<Read>,
    pub writes: Vec<Write>,
    /// Dynamic data dependencies: steps whose results this step consumed.
    pub deps: Vec<Step>,
    /// Dynamic control dependence: the last branch taken in this frame, i.e.
    /// the decision that made this step run at all.
    pub ctrl: Option<Step>,
    pub sync: Option<SyncOp>,
    pub nondet: Option<NondetKind>,
    /// Value pushed on the operand stack, if any (handy for "what did this
    /// expression evaluate to").
    pub result: Option<Val>,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum FaultKind {
    AssertionFailed,
    DivisionByZero,
    IndexOutOfBounds,
    TypeError,
    UnlockNotHeld,
    Panic,
    /// Every live thread is blocked. `cycle` is the wait-for cycle
    /// (thread, mutex it waits on), when there is one.
    Deadlock {
        cycle: Vec<(Tid, u32)>,
    },
}

impl FaultKind {
    pub fn label(&self) -> &'static str {
        match self {
            FaultKind::AssertionFailed => "assertion failed",
            FaultKind::DivisionByZero => "division by zero",
            FaultKind::IndexOutOfBounds => "index out of bounds",
            FaultKind::TypeError => "type error",
            FaultKind::UnlockNotHeld => "unlock of a mutex not held",
            FaultKind::Panic => "panic",
            FaultKind::Deadlock { .. } => "deadlock",
        }
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct Fault {
    pub kind: FaultKind,
    pub message: String,
    pub step: Step,
    pub tid: Tid,
    pub line: u32,
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Outcome {
    Completed,
    Fault(Fault),
    StepLimit { limit: Step },
}

impl Outcome {
    pub fn fault(&self) -> Option<&Fault> {
        match self {
            Outcome::Fault(f) => Some(f),
            _ => None,
        }
    }

    pub fn is_failure(&self) -> bool {
        !matches!(self, Outcome::Completed)
    }
}

#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct OutputLine {
    pub step: Step,
    pub tid: Tid,
    pub text: String,
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct TraceMeta {
    pub name: String,
    pub source: String,
    /// Only used to drive the recorder's chaos scheduler. Replay ignores it.
    pub seed: u64,
    pub chaos: f64,
    pub created_unix_ms: u64,
    pub engine: String,
}

/// What gets written to a `.cfrec` file.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Recording {
    pub meta: TraceMeta,
    pub nondet: Vec<NondetEvent>,
    pub outcome: Outcome,
    pub total_steps: Step,
    pub output: Vec<OutputLine>,
}
